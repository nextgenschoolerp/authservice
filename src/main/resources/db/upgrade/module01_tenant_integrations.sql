-- Settings → Integrations: one row per school and channel (EMAIL, SMS, WHATSAPP, PAYMENT).
-- settings_json holds the plain settings; secret_cipher holds the password / API key / token encrypted with AES-256-GCM
-- (key: KVS_INTEGRATIONS_KEY). No rows are seeded: provider credentials are entered by each school.
CREATE TABLE IF NOT EXISTS tenant_integrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone,
    created_by character varying(255),
    updated_at timestamp(6) with time zone,
    updated_by character varying(255),
    version bigint,
    tenant_id character varying(100) NOT NULL,
    channel character varying(20) NOT NULL,
    provider character varying(30) NOT NULL,
    enabled boolean NOT NULL,
    settings_json text,
    secret_cipher text,
    secret_hint character varying(8),
    status character varying(20) NOT NULL,
    last_test_at timestamp(6) with time zone,
    last_test_result character varying(500),
    CONSTRAINT tenant_integrations_pkey PRIMARY KEY (id),
    CONSTRAINT uk_tenant_integration_channel UNIQUE (tenant_id, channel)
);
